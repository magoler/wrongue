"""Private clipboard access for Wrongue.

What we put on the clipboard is marked so that clipboard-history apps,
Universal Clipboard (Mac) and Windows clipboard history / cloud sync skip it.
On Mac the full previous clipboard (images, files, rich text) is restored.
"""

import sys
import time

IS_MAC = sys.platform == "darwin"
IS_WIN = sys.platform.startswith("win")


# ======================= macOS =======================
if IS_MAC:
    from AppKit import NSPasteboard, NSPasteboardItem, NSPasteboardTypeString
    from Foundation import NSData

    # https://nspasteboard.org: honoured by Paste, Raycast, Alfred, Maccy, etc.
    _PRIVATE_MARKERS = ["org.nspasteboard.ConcealedType",
                        "org.nspasteboard.TransientType",
                        "org.nspasteboard.AutoGeneratedType"]
    _CURRENT_HOST_ONLY = 1  # NSPasteboardContentsCurrentHostOnly: no Universal Clipboard

    def _pb():
        return NSPasteboard.generalPasteboard()

    def change_count():
        return _pb().changeCount()

    def get_text():
        return _pb().stringForType_(NSPasteboardTypeString) or ""

    def save():
        """Snapshot every item and type currently on the clipboard."""
        snapshot = []
        for item in _pb().pasteboardItems() or []:
            data = {}
            for t in item.types():
                d = item.dataForType_(t)
                if d is not None:
                    data[t] = d
            snapshot.append(data)
        return snapshot

    def restore(snapshot):
        pb = _pb()
        pb.clearContents()
        items = []
        for data in snapshot:
            item = NSPasteboardItem.alloc().init()
            for t, d in data.items():
                item.setData_forType_(d, t)
            # It's already in the user's history; don't record it a second time.
            item.setData_forType_(NSData.data(), "org.nspasteboard.TransientType")
            items.append(item)
        if items:
            pb.writeObjects_(items)

    def set_private_text(text):
        pb = _pb()
        pb.prepareForNewContentsWithOptions_(_CURRENT_HOST_ONLY)
        pb.clearContents()
        pb.prepareForNewContentsWithOptions_(_CURRENT_HOST_ONLY)
        pb.setString_forType_(text, NSPasteboardTypeString)
        for marker in _PRIVATE_MARKERS:
            pb.setData_forType_(NSData.data(), marker)


# ======================= Windows =======================
elif IS_WIN:
    import ctypes
    from ctypes import wintypes

    _u32 = ctypes.WinDLL("user32", use_last_error=True)
    _k32 = ctypes.WinDLL("kernel32", use_last_error=True)
    _k32.GlobalAlloc.argtypes = [wintypes.UINT, ctypes.c_size_t]
    _k32.GlobalAlloc.restype = wintypes.HGLOBAL
    _k32.GlobalLock.argtypes = [wintypes.HGLOBAL]
    _k32.GlobalLock.restype = ctypes.c_void_p
    _k32.GlobalUnlock.argtypes = [wintypes.HGLOBAL]
    _u32.OpenClipboard.argtypes = [wintypes.HWND]
    _u32.GetClipboardData.argtypes = [wintypes.UINT]
    _u32.GetClipboardData.restype = wintypes.HANDLE
    _u32.SetClipboardData.argtypes = [wintypes.UINT, wintypes.HANDLE]
    _u32.SetClipboardData.restype = wintypes.HANDLE
    _u32.RegisterClipboardFormatW.argtypes = [wintypes.LPCWSTR]
    _u32.RegisterClipboardFormatW.restype = wintypes.UINT
    _u32.GetClipboardSequenceNumber.restype = wintypes.DWORD

    CF_UNICODETEXT = 13
    GMEM_MOVEABLE = 0x0002

    def _open():
        for _ in range(25):
            if _u32.OpenClipboard(None):
                return
            time.sleep(0.02)
        raise OSError("clipboard is busy")

    def _global(data):
        h = _k32.GlobalAlloc(GMEM_MOVEABLE, len(data))
        p = _k32.GlobalLock(h)
        ctypes.memmove(p, data, len(data))
        _k32.GlobalUnlock(h)
        return h

    def change_count():
        return _u32.GetClipboardSequenceNumber()

    def get_text():
        _open()
        try:
            h = _u32.GetClipboardData(CF_UNICODETEXT)
            if not h:
                return ""
            p = _k32.GlobalLock(h)
            try:
                return ctypes.wstring_at(p)
            finally:
                _k32.GlobalUnlock(h)
        finally:
            _u32.CloseClipboard()

    def save():
        return get_text()  # Windows: text only

    def _set(text, private):
        _open()
        try:
            _u32.EmptyClipboard()
            if text:
                _u32.SetClipboardData(CF_UNICODETEXT, _global(text.encode("utf-16-le") + b"\0\0"))
            if private:
                # Keep it out of Win+V history and cloud clipboard sync.
                zero = (0).to_bytes(4, "little")
                for name in ("ExcludeClipboardContentFromMonitorProcessing",
                             "CanIncludeInClipboardHistory",
                             "CanUploadToCloudClipboard"):
                    _u32.SetClipboardData(_u32.RegisterClipboardFormatW(name), _global(zero))
        finally:
            _u32.CloseClipboard()

    def restore(snapshot):
        _set(snapshot, private=True)

    def set_private_text(text):
        _set(text, private=True)


# ======================= other =======================
else:
    import pyperclip

    def change_count():
        return pyperclip.paste()

    def get_text():
        return pyperclip.paste() or ""

    def save():
        return get_text()

    def restore(snapshot):
        pyperclip.copy(snapshot)

    def set_private_text(text):
        pyperclip.copy(text)
